/*
 * chart_fuzzer — fuzz the libxlsxwriter chart module (src/chart.c is 100%
 * dark under the existing harness: 3,447 dark lines, 314 dark functions).
 *
 * Threat model:
 *   * Untrusted input: chart definitions in real applications are built from
 *     user data — series names, category/value ranges, axis bounds, title and
 *     legend strings, number formats. The chart writer must not violate
 *     memory safety for any combination of those, nor for absurd numeric
 *     axis bounds or invalid enum values (documented API inputs).
 *   * Trust boundary: the public chart_* APIs driven here, over an attacker-
 *     shaped worksheet grid.
 *   * Held fixed: workbook/worksheet lifecycle, sheet name 'Sheet1', chart
 *     objects created via workbook_add_chart (library-owned), and the output
 *     path (mkstemp temp file, unlinked after workbook_close).
 *   * Expected bug classes: memory safety in series/points/labels handling,
 *     axis numeric edge cases (min/max crossing, log_base, interval units),
 *     XML escaping of attacker title/series-name strings, enum handling.
 *
 * Caller-allocated option structs (line/fill/pattern/font/layout/points) are
 * stack-local: the library deep-copies them (verified _chart_convert_*_args),
 * so nothing leaks and no caller-side lifetime issues exist.
 *
 * Input shape: an op stream; each op consumes a fixed FuzzedDataProvider
 * sequence, every draw as its own statement. Seeds are generated by
 * dev/fuzzing/generate_chart_seeds.py mirroring that order.
 */
#include <cstdint>
#include <cstring>
#include <string>
#include <unistd.h>

#include <fuzzer/FuzzedDataProvider.h>

#include "xlsxwriter.h"

namespace {

const std::string mem_dir = "/dev/shm";
const std::string file_template = "/chfuzzXXXXXX";
char temp_file_dir[FILENAME_MAX] = {0};

const size_t kMaxStr = 48;
const uint8_t kNumOps = 24;
const uint8_t kMaxCharts = 4;

int init_for_fuzzing()
{
    if (0 == access(mem_dir.c_str(), W_OK | R_OK))
        memcpy(temp_file_dir, mem_dir.c_str(), strnlen(mem_dir.c_str(), FILENAME_MAX));
    else
    {
        const char *tmp_prefix = getenv("TMPDIR");
        if (nullptr == tmp_prefix)
            tmp_prefix = "/tmp";
        memcpy((void *)temp_file_dir, tmp_prefix, strnlen(tmp_prefix, FILENAME_MAX));
    }
    return 0;
}

lxw_row_t draw_row(FuzzedDataProvider &fdp)
{
    return fdp.ConsumeIntegralInRange<lxw_row_t>(0, 40);
}

lxw_col_t draw_col(FuzzedDataProvider &fdp)
{
    return fdp.ConsumeIntegralInRange<lxw_col_t>(0, 12);
}

std::string draw_str(FuzzedDataProvider &fdp)
{
    return fdp.ConsumeRandomLengthString(kMaxStr);
}

double draw_double(FuzzedDataProvider &fdp)
{
    return (double)fdp.ConsumeIntegralInRange<int32_t>(-100000, 100000) / 64.0;
}

uint8_t draw_byte(FuzzedDataProvider &fdp)
{
    return fdp.ConsumeIntegral<uint8_t>();
}

uint16_t draw_u16(FuzzedDataProvider &fdp)
{
    return fdp.ConsumeIntegral<uint16_t>();
}

} // namespace

extern "C" int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
    static bool init_fuzzing = init_for_fuzzing();
    (void)init_fuzzing;

    char fuzz_file[FILENAME_MAX + 1] = {0};
    strncpy(fuzz_file, temp_file_dir, strlen(temp_file_dir));
    strncat(fuzz_file, file_template.c_str(), file_template.length());

    int fuzz_fd = mkstemp(fuzz_file);
    if (fuzz_fd < 0)
        return 0;

    FuzzedDataProvider fdp(data, size);

    lxw_workbook *workbook = workbook_new(fuzz_file);
    if (nullptr == workbook)
    {
        close(fuzz_fd);
        unlink(fuzz_file);
        return 0;
    }

    lxw_worksheet *worksheet = workbook_add_worksheet(workbook, "Sheet1");

    /* A small attacker-shaped grid for series ranges to point at. */
    for (lxw_row_t r = 0; r < 9; r++)
    {
        for (lxw_col_t c = 0; c < 6; c++)
        {
            if (0 == r)
                worksheet_write_string(worksheet, r, c, "hdr", nullptr);
            else
                worksheet_write_number(worksheet, r, c,
                                       (double)(r * 6 + c) * 1.5 - 10.0, nullptr);
        }
    }

    lxw_chart *charts[kMaxCharts] = {nullptr, nullptr, nullptr, nullptr};
    lxw_chart_series *cur_series = nullptr;
    lxw_chart *cur = nullptr;
    uint8_t ncharts = 0;
    /* One-shot flags: these library setters strdup-overwrite without freeing
     * (finding LXW-4, _chart_set_range; title/name/num-format setters same
     * class), so the harness mirrors the legitimate idempotent pattern. */
    bool cur_cats_set = false;
    bool cur_vals_set = false;
    bool cur_series_name_set = false;
    bool cur_title_set = false;
    bool cur_legend_del_set = false;
    bool axis_name_set[2] = {false, false};
    bool axis_numfmt_set[2] = {false, false};

    int guard = 0;
    while (fdp.remaining_bytes() > 2 && guard++ < 48)
    {
        uint8_t op = draw_byte(fdp);
        if (op >= kNumOps)
            continue;

        lxw_row_t r1 = 0, r2 = 0;
        lxw_col_t c1 = 0, c2 = 0;
        std::string s1, s2;
        uint8_t b1 = 0, b2 = 0, b3 = 0;
        double d1 = 0.0, d2 = 0.0;
        uint16_t w1 = 0;

        switch (op)
        {
        case 0: /* add chart */
        {
            b1 = draw_byte(fdp);
            lxw_chart_type type = (lxw_chart_type)(b1 % 27);
            lxw_chart *ch = workbook_add_chart(workbook, type);
            if (nullptr != ch)
            {
                if (ncharts < kMaxCharts)
                    charts[ncharts++] = ch;
                else
                    charts[draw_byte(fdp) % kMaxCharts] = ch;
                cur = ch;
                cur_series = nullptr;
                cur_cats_set = false;
                cur_vals_set = false;
                cur_series_name_set = false;
                cur_title_set = false;
                cur_legend_del_set = false;
                axis_name_set[0] = axis_name_set[1] = false;
                axis_numfmt_set[0] = axis_numfmt_set[1] = false;
            }
            break;
        }
        case 1: /* add series with structured Sheet1 ranges.
                 * Finding LXW-3 (real, upstream): a tolerated unknown-sheet
                 * formula (the library only warns) reaches _chart_write_f()
                 * with a NULL formula and crashes in the XML escaper during
                 * cache writing. Series components stay fuzzed; the sheet
                 * token is fixed so the normal flow is exercised. The crash
                 * stays reproducible from the quarantined artefact. */
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            b3 = draw_byte(fdp);
            {
                char cats[64], vals[64];
                snprintf(cats, sizeof(cats), "=Sheet1!$%c$%d:$%c$%d",
                         'A' + (b1 % 6), 2 + (b2 % 7), 'A' + (b1 % 6),
                         3 + (b3 % 6));
                snprintf(vals, sizeof(vals), "=Sheet1!$%c$%d:$%c$%d",
                         'A' + (b3 % 6), 2 + (b2 % 7), 'A' + (b3 % 6),
                         3 + ((b2 >> 3) % 6));
                cur_series = chart_add_series(cur, cats, vals);
            }
            break;
        case 2: /* series categories by numbers */
            if (nullptr == cur_series || cur_cats_set)
                break;
            r1 = draw_row(fdp);
            c1 = draw_col(fdp);
            r2 = draw_row(fdp);
            c2 = draw_col(fdp);
            chart_series_set_categories(cur_series, "Sheet1", r1, c1, r2, c2);
            cur_cats_set = true;
            break;
        case 3: /* series values by numbers */
            if (nullptr == cur_series || cur_vals_set)
                break;
            r1 = draw_row(fdp);
            c1 = draw_col(fdp);
            r2 = draw_row(fdp);
            c2 = draw_col(fdp);
            chart_series_set_values(cur_series, "Sheet1", r1, c1, r2, c2);
            cur_vals_set = true;
            break;
        case 4: /* series name / name range */
        {
            if (nullptr == cur_series || cur_series_name_set)
                break;
            cur_series_name_set = true;
            s1 = draw_str(fdp);
            r1 = draw_row(fdp);
            c1 = draw_col(fdp);
            b1 = draw_byte(fdp);
            if (b1 & 1)
                chart_series_set_name(cur_series, s1.c_str());
            else
                chart_series_set_name_range(cur_series, "Sheet1", r1, c1);
            break;
        }
        case 5: /* series line/fill/pattern */
        {
            if (nullptr == cur_series)
                break;
            lxw_chart_line line;
            memset(&line, 0, sizeof(line));
            line.color = (lxw_color_t)0x9933FF;
            line.width = (double)(draw_byte(fdp)) + 0.5;
            line.dash_type = (uint8_t)(draw_byte(fdp) % 8);
            lxw_chart_fill fill;
            memset(&fill, 0, sizeof(fill));
            fill.color = (lxw_color_t)0x33CC99;
            fill.transparency = (uint8_t)(draw_byte(fdp) % 101);
            lxw_chart_pattern pattern;
            memset(&pattern, 0, sizeof(pattern));
            pattern.fg_color = (lxw_color_t)0x123456;
            pattern.bg_color = (lxw_color_t)0x654321;
            pattern.type = (uint8_t)(draw_byte(fdp) % 19);
            chart_series_set_line(cur_series, &line);
            chart_series_set_fill(cur_series, &fill);
            chart_series_set_pattern(cur_series, &pattern);
            break;
        }
        case 6: /* series points */
        {
            if (nullptr == cur_series)
                break;
            lxw_chart_line pline;
            memset(&pline, 0, sizeof(pline));
            pline.color = (lxw_color_t)0xFF00FF;
            lxw_chart_fill pfill;
            memset(&pfill, 0, sizeof(pfill));
            pfill.color = (lxw_color_t)0x00FF99;
            lxw_chart_point p1, p2, p3;
            memset(&p1, 0, sizeof(p1));
            memset(&p2, 0, sizeof(p2));
            memset(&p3, 0, sizeof(p3));
            p1.line = &pline;
            p1.fill = &pfill;
            p2.fill = &pfill;
            p3.line = &pline;
            lxw_chart_point *points[4] = {&p1, &p2, &p3, nullptr};
            chart_series_set_points(cur_series, points);
            break;
        }
        case 7: /* data labels */
        {
            if (nullptr == cur_series)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            b3 = draw_byte(fdp);
            chart_series_set_labels(cur_series);
            chart_series_set_labels_options(cur_series, b1 & 1, (b1 >> 1) & 1,
                                            (b1 >> 2) & 1);
            lxw_chart_font font;
            memset(&font, 0, sizeof(font));
            font.name = "fuzz";
            font.size = (double)(draw_byte(fdp) % 40) + 1.0;
            font.bold = b2 & 1;
            font.italic = (b2 >> 1) & 1;
            chart_series_set_labels_font(cur_series, &font);
            chart_series_set_labels_position(cur_series, (uint8_t)(b3 % 8));
            break;
        }
        case 8: /* error bars */
        {
            if (nullptr == cur_series)
                break;
            b1 = draw_byte(fdp);
            d1 = draw_double(fdp);
            b2 = draw_byte(fdp);
            b3 = draw_byte(fdp);
            chart_series_set_error_bars(cur_series->y_error_bars,
                                        (uint8_t)((b1 % 6) + 1), d1);
            chart_series_set_error_bars_direction(cur_series->y_error_bars,
                                                  (uint8_t)(b2 % 3));
            chart_series_set_error_bars_endcap(cur_series->x_error_bars, b3 & 1);
            break;
        }
        case 9: /* smooth / invert */
            if (nullptr == cur_series)
                break;
            b1 = draw_byte(fdp);
            chart_series_set_smooth(cur_series, b1 & 1);
            chart_series_set_invert_if_negative(cur_series);
            break;
        case 10: /* axis name / number format group */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp); /* axis select */
            b2 = draw_byte(fdp); /* sub-op */
            s1 = draw_str(fdp);
            r1 = draw_row(fdp);
            c1 = draw_col(fdp);
            lxw_chart_axis *ax = chart_axis_get(cur, (b1 & 1) ? LXW_CHART_AXIS_TYPE_Y
                                                              : LXW_CHART_AXIS_TYPE_X);
            if (nullptr == ax)
                break;
            switch (b2 % 5)
            {
            case 0:
                if (!axis_name_set[b1 & 1])
                {
                    chart_axis_set_name(ax, s1.c_str());
                    axis_name_set[b1 & 1] = true;
                }
                break;
            case 1:
                if (!axis_name_set[b1 & 1])
                {
                    chart_axis_set_name_range(ax, "Sheet1", r1, c1);
                    axis_name_set[b1 & 1] = true;
                }
                break;
            case 2:
            {
                lxw_chart_font font;
                memset(&font, 0, sizeof(font));
                font.name = "fuzz";
                font.size = (double)(draw_byte(fdp) % 30) + 2.0;
                chart_axis_set_name_font(ax, &font);
                break;
            }
            case 3:
            {
                lxw_chart_font nfont;
                memset(&nfont, 0, sizeof(nfont));
                nfont.name = "num";
                nfont.size = 9.0;
                nfont.rotation = (int32_t)(draw_byte(fdp) % 4) - 1;
                chart_axis_set_num_font(ax, &nfont);
                chart_axis_set_num_format(ax, s1.c_str());
                break;
            }
            default:
                chart_axis_set_num_format(ax, s1.c_str());
                break;
            }
            break;
        }
        case 11: /* axis numeric edges */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            d1 = draw_double(fdp);
            d2 = draw_double(fdp);
            w1 = draw_u16(fdp);
            lxw_chart_axis *ax = chart_axis_get(cur, (b1 & 1) ? LXW_CHART_AXIS_TYPE_Y
                                                              : LXW_CHART_AXIS_TYPE_X);
            if (nullptr == ax)
                break;
            switch (b2 % 6)
            {
            case 0:
                chart_axis_set_min(ax, d1);
                chart_axis_set_max(ax, d2);
                break;
            case 1:
                chart_axis_set_log_base(ax, (uint16_t)(w1 % 1001));
                break;
            case 2:
                chart_axis_set_crossing(ax, d1);
                break;
            case 3:
                chart_axis_set_crossing_max(ax);
                break;
            case 4:
                chart_axis_set_crossing_min(ax);
                break;
            default:
                chart_axis_set_major_unit(ax, (uint16_t)(w1 % 100));
                chart_axis_set_minor_unit(ax, (uint16_t)(w1 % 17));
                break;
            }
            break;
        }
        case 12: /* axis interval/display units */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            w1 = draw_u16(fdp);
            lxw_chart_axis *ax = chart_axis_get(cur, (b1 & 1) ? LXW_CHART_AXIS_TYPE_Y
                                                              : LXW_CHART_AXIS_TYPE_X);
            if (nullptr == ax)
                break;
            switch (b2 % 4)
            {
            case 0:
                chart_axis_set_interval_unit(ax, (uint16_t)(w1 % 1000));
                break;
            case 1:
                chart_axis_set_interval_tick(ax, (uint16_t)(w1 % 1000));
                break;
            case 2:
                chart_axis_set_display_units(ax, (uint8_t)(w1 % 7));
                break;
            default:
                chart_axis_set_display_units_visible(ax, w1 & 1);
                break;
            }
            break;
        }
        case 13: /* axis look: line/fill/pattern/reverse/off */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            lxw_chart_axis *ax = chart_axis_get(cur, (b1 & 1) ? LXW_CHART_AXIS_TYPE_Y
                                                              : LXW_CHART_AXIS_TYPE_X);
            if (nullptr == ax)
                break;
            lxw_chart_line line;
            memset(&line, 0, sizeof(line));
            line.color = (lxw_color_t)0x222222;
            line.width = (double)(draw_byte(fdp) % 10) + 0.25;
            lxw_chart_fill fill;
            memset(&fill, 0, sizeof(fill));
            fill.color = (lxw_color_t)0xEEEEEE;
            lxw_chart_pattern pattern;
            memset(&pattern, 0, sizeof(pattern));
            pattern.fg_color = (lxw_color_t)0xABABAB;
            pattern.type = (uint8_t)(draw_byte(fdp) % 19);
            switch (b2 % 5)
            {
            case 0:
                chart_axis_set_line(ax, &line);
                break;
            case 1:
                chart_axis_set_fill(ax, &fill);
                break;
            case 2:
                chart_axis_set_pattern(ax, &pattern);
                break;
            case 3:
                chart_axis_set_reverse(ax);
                break;
            default:
                chart_axis_off(ax);
                break;
            }
            break;
        }
        case 14: /* gridlines */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            lxw_chart_axis *ax = chart_axis_get(cur, (b1 & 1) ? LXW_CHART_AXIS_TYPE_Y
                                                              : LXW_CHART_AXIS_TYPE_X);
            if (nullptr == ax)
                break;
            lxw_chart_line gline;
            memset(&gline, 0, sizeof(gline));
            gline.color = (lxw_color_t)0xCCCCCC;
            gline.dash_type = (uint8_t)(draw_byte(fdp) % 8);
            switch (b2 % 4)
            {
            case 0:
                chart_axis_major_gridlines_set_visible(ax, 1);
                break;
            case 1:
                chart_axis_minor_gridlines_set_visible(ax, 1);
                break;
            case 2:
                chart_axis_major_gridlines_set_line(ax, &gline);
                break;
            default:
                chart_axis_minor_gridlines_set_line(ax, &gline);
                break;
            }
            break;
        }
        case 15: /* axis labels */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            b3 = draw_byte(fdp);
            lxw_chart_axis *ax = chart_axis_get(cur, (b1 & 1) ? LXW_CHART_AXIS_TYPE_Y
                                                              : LXW_CHART_AXIS_TYPE_X);
            if (nullptr == ax)
                break;
            chart_axis_set_label_position(ax, (uint8_t)(b2 % 4));
            chart_axis_set_label_align(ax, (uint8_t)(b3 % 4));
            chart_axis_set_position(ax, (uint8_t)((b3 >> 2) % 3));
            break;
        }
        case 16: /* chart title */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            s1 = draw_str(fdp);
            r1 = draw_row(fdp);
            c1 = draw_col(fdp);
            switch (b1 % 4)
            {
            case 0:
                if (!cur_title_set)
                {
                    chart_title_set_name(cur, s1.c_str());
                    cur_title_set = true;
                }
                break;
            case 1:
                if (!cur_title_set)
                {
                    chart_title_set_name_range(cur, "Sheet1", r1, c1);
                    cur_title_set = true;
                }
                break;
            case 2:
            {
                lxw_chart_font tfont;
                memset(&tfont, 0, sizeof(tfont));
                tfont.name = "tf";
                tfont.size = 14.0;
                tfont.bold = 1;
                chart_title_set_name_font(cur, &tfont);
                break;
            }
            default:
                chart_title_off(cur);
                break;
            }
            break;
        }
        case 17: /* legend */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            switch (b1 % 3)
            {
            case 0:
                chart_legend_set_position(cur, (uint8_t)(draw_byte(fdp) % 6));
                break;
            case 1:
            {
                lxw_chart_font lfont;
                memset(&lfont, 0, sizeof(lfont));
                lfont.name = "lg";
                lfont.size = 8.0;
                chart_legend_set_font(cur, &lfont);
                break;
            }
            default:
            {
                lxw_chart_layout layout;
                memset(&layout, 0, sizeof(layout));
                layout.x = draw_double(fdp);
                layout.y = draw_double(fdp);
                layout.width = draw_double(fdp);
                layout.height = draw_double(fdp);
                chart_legend_set_layout(cur, &layout);
                break;
            }
            }
            break;
        }
        case 18: /* legend delete series */
        {
            if (nullptr == cur || cur_legend_del_set)
                break;
            cur_legend_del_set = true;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            int16_t del[3] = {(int16_t)(b1 % 8), (int16_t)(b2 % 8), -1};
            chart_legend_delete_series(cur, del);
            break;
        }
        case 19: /* plotarea / chartarea */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            lxw_chart_line line;
            memset(&line, 0, sizeof(line));
            line.color = (lxw_color_t)0x336699;
            lxw_chart_fill fill;
            memset(&fill, 0, sizeof(fill));
            fill.color = (lxw_color_t)0xF0F0F0;
            fill.transparency = (uint8_t)(draw_byte(fdp) % 101);
            lxw_chart_pattern pattern;
            memset(&pattern, 0, sizeof(pattern));
            pattern.fg_color = (lxw_color_t)0x777777;
            pattern.type = (uint8_t)(draw_byte(fdp) % 19);
            lxw_chart_layout layout;
            memset(&layout, 0, sizeof(layout));
            layout.x = draw_double(fdp);
            layout.y = draw_double(fdp);
            switch (b1 & 1)
            {
            case 0:
                switch (b2 % 4)
                {
                case 0:
                    chart_plotarea_set_line(cur, &line);
                    break;
                case 1:
                    chart_plotarea_set_fill(cur, &fill);
                    break;
                case 2:
                    chart_plotarea_set_pattern(cur, &pattern);
                    break;
                default:
                    chart_plotarea_set_layout(cur, &layout);
                    break;
                }
                break;
            default:
                switch (b2 % 4)
                {
                case 0:
                    chart_chartarea_set_line(cur, &line);
                    break;
                case 1:
                    chart_chartarea_set_fill(cur, &fill);
                    break;
                case 2:
                    chart_chartarea_set_pattern(cur, &pattern);
                    break;
                default:
                    chart_chartarea_set_line(cur, &line);
                    break;
                }
                break;
            }
            break;
        }
        case 20: /* chart misc group */
        {
            if (nullptr == cur)
                break;
            b1 = draw_byte(fdp);
            b2 = draw_byte(fdp);
            w1 = draw_u16(fdp);
            lxw_chart_line line;
            memset(&line, 0, sizeof(line));
            line.color = (lxw_color_t)0x555555;
            switch (b1 % 7)
            {
            case 0:
                chart_set_style(cur, (uint8_t)((b2 % 48) + 1));
                break;
            case 1:
                chart_set_rotation(cur, w1);
                break;
            case 2:
                chart_set_hole_size(cur, (uint8_t)(b2 % 101));
                break;
            case 3:
                chart_set_up_down_bars(cur);
                break;
            case 4:
                chart_set_drop_lines(cur, &line);
                break;
            case 5:
                chart_set_high_low_lines(cur, &line);
                break;
            default:
                chart_show_blanks_as(cur, (uint8_t)(b2 % 3));
                break;
            }
            break;
        }
        case 21: /* insert chart into worksheet */
            if (nullptr == cur)
                break;
            r1 = draw_row(fdp);
            c1 = draw_col(fdp);
            worksheet_insert_chart(worksheet, r1, c1, cur);
            break;
        case 22: /* insert chart with offsets */
        {
            if (nullptr == cur)
                break;
            r1 = draw_row(fdp);
            c1 = draw_col(fdp);
            lxw_chart_options copts;
            memset(&copts, 0, sizeof(copts));
            copts.x_offset = (int32_t)draw_byte(fdp);
            copts.y_offset = (int32_t)draw_byte(fdp);
            worksheet_insert_chart_opt(worksheet, r1, c1, cur, &copts);
            break;
        }
        case 23: /* chartsheet */
        {
            s1 = draw_str(fdp);
            s2 = draw_str(fdp);
            b1 = draw_byte(fdp);
            lxw_chartsheet *cs = workbook_add_chartsheet(workbook,
                                                         s1.empty() ? nullptr : s1.c_str());
            if (nullptr != cs)
            {
                if (nullptr != cur)
                    chartsheet_set_chart(cs, cur);
                chartsheet_set_header(cs, s2.c_str());
                chartsheet_set_tab_color(cs, (lxw_color_t)0x99FF99);
                chartsheet_set_zoom(cs, (uint16_t)(b1 * 4 + 50));
                chartsheet_set_landscape(cs);
            }
            break;
        }
        }
    }

    workbook_close(workbook);
    close(fuzz_fd);
    unlink(fuzz_file);
    return 0;
}
